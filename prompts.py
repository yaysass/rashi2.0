def _filter_themes(section_key: str, dominant_themes: list[dict]) -> list[dict]:
    """Filter dominant_themes to those whose areas overlap with the section."""
    relevant = set(SECTION_AREAS.get(section_key, []))
    if not relevant:
        return dominant_themes
    return [
        t for t in dominant_themes
        if set(t.get("areas", [])) & relevant
    ]


def _planet_compact(en_name: str, planets: dict) -> str | None:
    p = planets.get(en_name)
    if not p:
        return None
    ru = PLANET_NAMES_RU.get(en_name, en_name)
    parts = [f"{ru}: {p['sign']}"]
    if p.get("house"):
        parts.append(f"дом {p['house']}")
    if p.get("retro"):
        parts.append("ретро")
    return ", ".join(parts)


def _extract_anchors(section_key: str, astro_json: dict) -> dict[str, str]:
    """Build a compact chart_anchors dict relevant for the given section."""
    raw      = astro_json.get("raw", {})
    planets  = raw.get("planets", {})
    lagna    = raw.get("ascendant", {})
    dasha    = raw.get("dasha", {})

    anchors: dict[str, str] = {}

    lagna_sign = lagna.get("sign", "")
    if lagna_sign:
        anchors["лагна"] = lagna_sign

    # Planets for this section
    for en in _SECTION_PLANETS.get(section_key, []):
        info = _planet_compact(en, planets)
        if info:
            anchors[PLANET_NAMES_RU[en].lower()] = info

    # Houses for this section
    for h in _SECTION_HOUSES.get(section_key, []):
        if lagna_sign:
            h_sign = _house_sign(lagna_sign, h)
            if h_sign:
                anchors[f"дом_{h}"] = h_sign
                ruler = SIGN_RULERS.get(h_sign, "")
                if ruler:
                    r_en = PLANET_RU_TO_EN.get(ruler)
                    if r_en:
                        r_info = _planet_compact(r_en, planets)
                        if r_info:
                            anchors[f"управитель_дома_{h}"] = r_info

    # Dasha data (always useful for years/dasha sections)
    if section_key in ("years", "dasha_adv", "transit_year", "personality"):
        if dasha.get("maha"):
            anchors["маха_даша"] = dasha["maha"]
        if dasha.get("antar"):
            anchors["антар_даша"] = dasha["antar"]
        if dasha.get("until"):
            anchors["антар_до"] = dasha["until"]

    return anchors


_CHALLENGE_KW = {
    "страх", "тревог", "сложность", "трудность", "избегание",
    "перфекционизм", "самокритик", "уязвимость", "подавленн",
    "скованность", "блокировк", "конфликт",
}

_STRENGTH_KW = {
    "сила", "умение", "способность", "глубок", "дипломатичн",
    "верность", "стабильность", "интуиция", "мудрость",
    "харизма", "чуткость", "надёжность",
}


def _derive_patterns(themes: list[dict]) -> list[str]:
    return [t["tag"] for t in themes[:3]]


def _derive_strengths(themes: list[dict]) -> list[str]:
    out = [t["tag"] for t in themes if any(kw in t["tag"].lower() for kw in _STRENGTH_KW)]
    return out[:3] if out else ([themes[0]["tag"]] if themes else [])


def _derive_blind_spots(themes: list[dict]) -> list[str]:
    out = [t["tag"] for t in themes if any(kw in t["tag"].lower() for kw in _CHALLENGE_KW)]
    return out[:2]


