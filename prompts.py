def _house_sign(lagna_sign: str, house: int) -> str:
    """Whole-sign house: знак N-го дома от Лагны."""
    try:
        idx = SIGNS_ORDER.index(lagna_sign)
        return SIGNS_ORDER[(idx + house - 1) % 12]
    except ValueError:
        return ""


