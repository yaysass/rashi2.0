# ── Контракт входных данных от бэкенда ────────────────────────────────────────

@dataclass
class Dossier:
    """
    Досье от бэкенда. Результат уровней 1-3 (взвешивание мотивов и поиск сигнала).
    Claude получает уже отфильтрованный смысл, а не сырую карту.

    dominant_themes : мотивы, отсортированные по убыванию веса.
                      Пример: ["Контроль", "Аналитика", "Скрытая уязвимость"]
    central_conflict: готовая формула центрального конфликта (уровень 5).
                      Пример: "Тяга к лёгкости и паре, но потребность в жёстком
                               контроле и дистанции: близость пугает так же,
                               как одиночество."
    raw_signals     : технические маркеры (санскрит/планеты/дома) - ТОЛЬКО сырьё.
                      В ответе их быть не должно. Может быть пустым.
    extra           : произвольные поля под конкретный раздел (периоды, событие и т.д.)
    """
    dominant_themes: list[str] = field(default_factory=list)
    central_conflict: str = ""
    raw_signals: list[str] = field(default_factory=list)
    extra: dict = field(default_factory=dict)

    def to_prompt_block(self) -> str:
        parts: list[str] = []
        if self.dominant_themes:
            ranked = "\n".join(
                f"  {i}. {t}" for i, t in enumerate(self.dominant_themes, 1)
            )
            parts.append(
                "ГЛАВНЫЕ ПОВТОРЯЮЩИЕСЯ СИГНАЛЫ КАРТЫ "
                "(по убыванию веса, верхние — ось всего разбора):\n" + ranked
            )
        if self.central_conflict:
            parts.append("ЦЕНТРАЛЬНЫЙ КОНФЛИКТ ЯДРА:\n  " + self.central_conflict)
        if self.raw_signals:
            parts.append(
                "СЫРЫЕ МАРКЕРЫ (только как сырьё для понимания, "
                "в ответе их быть НЕ должно):\n  " + "; ".join(self.raw_signals)
            )
        for key, val in self.extra.items():
            parts.append(f"{key}:\n  {val}")
        return "\n\n".join(parts)


# Тип входа карты: либо досье, либо dict-JSON из ТЗ, либо старая строка astro
AstroInput = Union[Dossier, str, dict]


def _astro_block(astro: AstroInput) -> str:
    """Нормализует вход: Dossier / dict / legacy-строка -> текстовый блок для промпта."""
    if isinstance(astro, Dossier):
        return astro.to_prompt_block()
    if isinstance(astro, dict):
        # JSON-досье в формате из ТЗ
        return Dossier(
            dominant_themes=astro.get("dominant_themes", []),
            central_conflict=astro.get("central_conflict", ""),
            raw_signals=astro.get("astrological_basis", astro.get("raw_signals", [])),
            extra={k: v for k, v in astro.items()
                   if k not in {"dominant_themes", "central_conflict",
                                "astrological_basis", "raw_signals", "question"}},
        ).to_prompt_block()
    # legacy: просто строка с положениями планет
    return f"Данные карты:\n{astro}"


