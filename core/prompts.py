def build_user_prompt(
    section_key: str,
    astro_json: dict[str, Any],
    user_name: str,
    gender: str,
    **extra,
) -> str:
    """
    Build the user-side message for Claude.

    Args:
        section_key:   key from READINGS catalog (e.g. "love", "money")
        astro_json:    full astro_json dict from User.get_astro()
        user_name:     first name from onboarding
        gender:        "male" | "female"
        **extra:       section-specific params:
                         question=str, event=str, period=str, week=str,
                         name1/name2/anchors1/anchors2 for synastry,
                         child_name for child reading

    Returns:
        Formatted prompt string to pass as the user message to Claude.
    """
    features        = astro_json.get("features", {})
    dominant_themes = features.get("dominant_themes", [])
    central_conflict = features.get("central_conflict", "не определено")

    # Filter themes for this section
    themes = _filter_themes(section_key, dominant_themes)

    # Build chart anchors
    anchors = _extract_anchors(section_key, astro_json)

    # Derive patterns / strengths / blind spots
    patterns    = _derive_patterns(themes)
    strengths   = _derive_strengths(themes)
    blind_spots = _derive_blind_spots(themes)

    # Format each component
    gender_ru = "мужской" if gender == "male" else "женский"

    anchors_lines = "\n".join(f"  {k}: {v}" for k, v in anchors.items() if v)
    anchors_block = anchors_lines or "  (данные карты ещё загружаются)"

    themes_lines = "\n".join(
        f"  - {t['tag']}  [вес: {t['weight']}]"
        for t in themes
    )
    themes_block = themes_lines or "  (темы не определены)"

    patterns_str    = "; ".join(patterns) if patterns else "—"
    strengths_str   = "; ".join(strengths) if strengths else "—"
    blind_spots_str = "; ".join(blind_spots) if blind_spots else "—"

    # Section instruction (format with extra params)
    raw_instruction = _SECTION_INSTRUCTIONS.get(
        section_key,
        _SECTION_INSTRUCTIONS["personality"],
    )
